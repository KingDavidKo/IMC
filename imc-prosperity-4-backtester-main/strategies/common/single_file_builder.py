import ast
from pathlib import Path


def resolve_local_module(root: Path, module_name: str) -> Path | None:
    parts = module_name.split(".")
    module_file = root.joinpath(*parts).with_suffix(".py")
    if module_file.exists():
        return module_file
    package_init = root.joinpath(*parts, "__init__.py")
    if package_init.exists():
        return package_init
    return None


def node_source(source: str, node: ast.AST) -> str:
    lines = source.splitlines(keepends=True)
    start = node.lineno - 1
    end = node.end_lineno
    return "".join(lines[start:end])


def render_module(path: Path, root: Path, visited: set[Path], import_lines: list[str]) -> list[str]:
    path = path.resolve()
    if path in visited:
        return []
    visited.add(path)

    source = path.read_text()
    tree = ast.parse(source, filename=str(path))
    output: list[str] = []

    for node in tree.body:
        if isinstance(node, ast.ImportFrom) and node.module:
            local_path = resolve_local_module(root, node.module)
            if local_path is not None:
                output.extend(render_module(local_path, root, visited, import_lines))
                continue

        if isinstance(node, (ast.Import, ast.ImportFrom)):
            import_line = node_source(source, node)
            if import_line not in import_lines:
                import_lines.append(import_line)
            continue

        output.append(node_source(source, node))

    return output


def build(entry_file: Path, output_file: Path) -> None:
    root = entry_file.parent.resolve()
    import_lines: list[str] = []
    body = render_module(entry_file.resolve(), root, set(), import_lines)

    rendered = [
        "# Generated by scripts/build_strategy.py. Edit the source modules instead.\n",
        "\n",
    ]
    rendered.extend(import_lines)
    if import_lines and import_lines[-1] != "\n":
        rendered.append("\n")
    rendered.extend(body)

    output_file.write_text("".join(rendered))
